"""Regenerate the achievement reference from the canonical Rust catalogue."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[2]
source = (ROOT / "crates/ta_config/src/achievements.rs").read_text(encoding="utf-8")
pattern = r'^\s*(a|hidden)\(("[^"\n]+"), ("[^"\n]+"), ("[^"\n]+"), C::(\w+), T::(\w+), "[^"\n]+", '
entries = [(kind == "hidden", json.loads(i), json.loads(n), json.loads(d), c, t)
           for kind, i, n, d, c, t in re.findall(pattern, source, re.MULTILINE)]
assert len(entries) >= 100, "catalogue syntax changed: update this exporter"
CATEGORIES = [("Campaign", "Campaign"), ("Skirmish", "Skirmish"), ("Multiplayer", "Multiplayer"),
              ("Battle", "Battle"), ("Industry", "Industry: construction and economy"), ("Service", "Service: rank and career")]
counts = ", ".join(f"{sum(1 for e in entries if e[4] == c)} {c.lower()}" for c, _ in CATEGORIES)
tiers = ", ".join(f"{sum(1 for e in entries if e[5] == t)} {t.lower()}" for t in ["Bronze", "Silver", "Gold", "Platinum"])
intro = f"""# Achievements and career records

This reference is generated by `python tools/profiles/export_achievements.py` from
`crates/ta_config/src/achievements.rs`. The game has **{len(entries)} achievements**: {counts};
by tier, {tiers}. Secret achievements are listed here as the game shows them until they are
earned: without their names or what they ask.

## Badges, notices and pictures

Each achievement has a badge (`crates/ta_ui/badges/achievements.png`, drawn by
`python tools/profiles/badges.py` from the catalogue): its glyph and rim struck in the metal of
its tier (bronze; silver with a beaded rim; gold in a laurel; platinum with a crest star and
gems) over an enamel field in its category's colour. A badge not earned is shown greyed.

An achievement earned in a battle comes up as a notice at the top right of the view, with its
badge, tier and what it asked, and the game keeps a picture of that moment: the battle as the
camera saw it, without the interface (a JPEG in the profile's `achievements` folder). The
career's ledger records where and when in the battle each was earned. The dossier lists them
with filters (category, earned or not, a search) and sorts (recently earned, nearest to
earning, rarest tier), and a chosen one's page shows its badge, progress, date and picture.

Between its checkpoints (every thirty seconds of battle) the game looks ahead once a second:
when something is earned, the battle is saved to the career at once, so the notice and the
picture come at the moment it happens.

## Eligibility and persistence

Achievements use the same local profile ledger as career XP. Only ordinary live play
counts. Replays, benchmarks, demonstrations, capture runs and spectators cannot generate new
progress. A battle in which cheats are used earns nothing: as the first cheat is used, what
it had earned is taken back (its XP, its share of the totals and single-battle records, the
campaign missions it completed first, and the achievements it unlocked that the career no
longer meets, with their pictures), and no copy of its saves can earn again. Other battles'
progress remains intact.
Unlocks persist by stable identifier and notify only once. Each grants XP by its tier
(bronze 100, silver 250, gold 500, platinum 1,000), counted toward the rank with the battles'
XP; an achievement's XP can raise the rank to another rank achievement in the same checkpoint.
Profile data never changes deterministic simulation state or multiplayer messages.

Campaign achievements count individually verified mission victories, including separate
Hard completion records. Playing the same mission again as a new battle contributes to
battle-win totals but not to the unique-mission count. Skirmish Hard victories require
every enemy AI to be set to Hard; "alone" means no allied player at all. Multiplayer
achievements require an active network session and at least one opposing human playing slot
(co-op wins need another person on your team); an offline setup or an AI-only network lobby
cannot earn them. All actual network sessions, including co-op, still appear as Multiplayer
in history and mode statistics; the PvP counters are kept separately.

A battle's records (units destroyed or built in one battle, the highest income, the army at
its largest, a Commander's kills) count the moment they are reached, and only when this
profile has tracked the battle from its beginning; outcome feats (a flawless or fast win, a
win against the odds) when it is won. Importing a partially played save cannot claim the
original player's records. Kills by class (Commanders, aircraft, ships, buildings,
experimentals: mobile units costing at least 8,000 metal) count enemies destroyed by your own
units. Ongoing matches checkpoint their real counters; reloading a save, reconnecting or
repeating a checkpoint cannot duplicate progress. A concluded match cannot earn an alternate
ending or further awards.

## Earlier play

The list was redone after version 2.1. A career recorded before it keeps the achievements whose
identifiers carried over (with their dates); those dropped from the list are removed. Opening
the profile (in the launcher or the game) then unlocks whatever the career's real totals
already meet, marked as earned from the service record, without a picture. Counters the
earlier ledger did not keep (event tallies, maps and worlds won on, battle records) start when
observed; they are never invented retroactively. Existing campaign unlock progress remains
visible separately from verified mission wins.

Favourite faction means the most eligible playing time; favourite unit means the most
completed constructions, including buildings. History displays recorded map, mode,
faction, result, duration and earned XP. Imported history includes only newly observed
play. Save and match identities remain in the bounded ledger to prevent old records
becoming eligible again. A full or malformed ledger reports an error without resetting
career data. Achievements are local accomplishments, not a competitive anti-cheat service.
"""
REWARD = {"Bronze": "100", "Silver": "250", "Gold": "500", "Platinum": "1,000"}  # Tier::reward
lines = [intro]
for category, title in CATEGORIES:
    rows = [e for e in entries if e[4] == category]
    lines += [f"\n## {title} ({len(rows)})\n", "| Achievement | Tier | XP | Requirement | Stable ID |", "| --- | --- | --- | --- | --- |"]
    for hidden, i, n, d, c, t in rows:
        lines.append(f"| *Secret achievement* | {t} | {REWARD[t]} | Revealed when earned. | `{i}` |" if hidden else f"| {n} | {t} | {REWARD[t]} | {d} | `{i}` |")
(ROOT / "docs/ACHIEVEMENTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\r\n")
print(f"Wrote docs/ACHIEVEMENTS.md ({len(entries)} achievements)")
